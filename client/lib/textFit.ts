/**
 * 한 줄짜리 글이 상자를 넘지 않도록 **글자 크기를 폭에 맞추는** 도구.
 *
 * 행동(기술) 카드의 설명·대사는 줄 수가 정해져 있다(설명 2줄 + 대사 1줄, 효과 라벨은
 * 쉼표마다 한 줄). 그런데 카드 폭은 액자 그림이 정하고 해상도마다 다르므로
 * (1920에서 223px · 1366에서 158px), 글자 크기를 화면 높이(vh)에만 묶어 두면 좁은
 * 해상도에서 마지막 한두 글자가 다음 줄로 흘러내린다 — 1600×900에서 설명이 3줄,
 * 대사가 2줄이 되던 것이 그 증상이다.
 *
 * 예전에는 clamp 상한을 눈대중으로 내려 막았지만, 글꼴을 바꾸거나 문구를 고칠 때마다
 * 다시 흘러내렸다. **CSS에는 "이 글이 몇 픽셀인가"라는 개념이 없어서** 상한값이
 * 언제나 추측일 수밖에 없다. 그래서 여기서 글의 폭을 em 단위로 **재어** 넘기고,
 * CSS가 `가용폭 ÷ em`으로 크기를 정한다(`font-size: min(상한, 100cqw / var(--em))`).
 *
 * ── 표의 숫자는 짐작이 아니라 실측이다 ──────────────────────────────────
 * 헤드리스 Chrome에 글자를 하나씩 200px로 그려 advance width를 그대로 읽었다
 * (`scripts/_ls.mjs` 방식). 그래서 문구 전체를 다시 재도 오차가 1% 안쪽이다:
 *   "동물을 더 뽑아 기회를 선점합니다."      예측 14.76em · 실측 14.76em
 *   "빠르게 등록해 실리를 챙기는 내 권리!"  예측 16.90em · 실측 16.90em
 *   "인어 레벨(0)만큼 (중첩가능)"            예측 12.33em · 실측 12.28em
 *
 * ⚠️ **가는 얼굴(Air)과 굵은 얼굴(v2.0)의 글자 폭은 같다.** 굵기만 다른 한 가족이라
 *    자간이 서로 맞춰져 있다 — 실측에서도 같은 문구가 14.756em과 14.770em으로
 *    나왔다(차이 0.1%). 그래서 얼굴별 보정이 없다. 다른 가족의 글꼴을 섞게 되면
 *    이 전제가 깨지므로 그때는 표를 다시 재야 한다.
 */

/** 한글 음절 — 전각에 가깝지만 정확히 1em은 아니다(모든 음절이 같은 폭이다). */
const W_HANGUL = 0.95;

/** 표에 없는 글자 — 라틴 대문자(0.72)보다 넉넉하게 잡아 모자라지 않게 한다. */
const W_FALLBACK = 0.75;

/** 화면에 실제로 쓰이는 글자들의 advance width(em). */
const W: Record<string, number> = {
  ' ': 0.295,
  '.': 0.28, ',': 0.28, '!': 0.295, '?': 0.591, ':': 0.308,
  '(': 0.383, ')': 0.382, '[': 0.459, ']': 0.457, '"': 0.44, "'": 0.241,
  '+': 0.607, '-': 0.58, '×': 0.701, '/': 0.673,
  '0': 0.706, '1': 0.518, '2': 0.646, '3': 0.718, '4': 0.658,
  '5': 0.718, '6': 0.736, '7': 0.670, '8': 0.718, '9': 0.718,
};

/** 한글·한자·가나 — 전각에 가까운 글자들 */
const FULLWIDTH = /[ᄀ-ᇿ㄰-㆏가-힯぀-ヿ一-鿿]/;

/**
 * 여유 — 표가 정확해도 브라우저의 자간 반올림·힌팅으로 1px 안쪽에서 어긋날 수 있다.
 * ⚠️ **모자라게 잡는 쪽만 위험하다.** 넉넉히 잡으면 글자가 필요보다 조금 작아질
 *    뿐이지만, 모자라게 잡으면 그대로 줄이 흘러넘친다.
 */
const SAFETY = 1.03;

/**
 * 여러 줄 글에서 **가장 긴 줄**의 폭을 em으로 돌려준다.
 * 줄바꿈(`\n`)으로 나뉜 각 줄을 따로 재므로, 그대로 CSS의 나눗셈 분모로 쓰면 된다.
 */
export function maxLineEm(text: string): number {
  let max = 0;
  for (const line of text.split('\n')) {
    let em = 0;
    for (const ch of line) em += W[ch] ?? (FULLWIDTH.test(ch) ? W_HANGUL : W_FALLBACK);
    if (em > max) max = em;
  }
  return Math.max(1, max * SAFETY);
}

/** CSS에 넘길 형태 — `font-size: min(상한, calc(가용폭 / var(--em)))`이 이 값을 쓴다. */
export function emVar(name: string, text: string): React.CSSProperties {
  return { [`--${name}` as string]: maxLineEm(text).toFixed(2) };
}
